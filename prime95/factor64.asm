	shr	ecx, 1
	cmp	ecx, edx
	jg	short setlp
	mov	shifter, eax		; Save unused bits in the shifter
	mov	temp, ecx		; Compute 2^ecx
	fild	temp
	fld1
	fscale
	fst	initval			; Save 2^ecx
	fld1
	fxch	st(1)
	fdivp	st(1), st
