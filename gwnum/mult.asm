; Jmptable definitions

; The flags word of a procedure entry is divided as follows:
;	80000000h		always on
;	4 SHL 26		(no prefetching)
;	2 SHL 26		(tlb priming)
;	1 SHL 26		(in_place)
;	fft_type SHL 18		(hg=0, r4=1, r4spm=2, r4r8=3, r4delay=4)
;	arch SHL 14		(ppro=0,p3=1,p4=2,core=3,k8=4,k10=5)
;	min_L2_cache SHL 10	(0=0,128KB=1,WILLI=2,CELE_D=3,512KB=4,1024KB=5,2048KB=6)
;	clm SHL 6		(1,2,4,8)
;	pass2size_over_256	(0,1,4,8,16,32)

X87PRC MACRO procname, mem_needed, p2larg, clmarg
	EXTRN	procname:PROC
	IF (@INSTR (,@CATSTR(procname),PPRO)) NE 0
		arch = 0
	ELSEIF (@INSTR (,@CATSTR(procname),P3)) NE 0
		arch = 1
	ELSE
		bad_x87_arch
	ENDIF
	IFB <clmarg>
		clm = 0
	ELSE
		clm = clmarg
	ENDIF
	IFB <p2larg>
		pass2_size_over_256 = 0
	ELSE
		pass2_size_over_256 = (1 SHL p2larg) SHR 8
	ENDIF
	flags = 0
	;; Kludge - if mem_needed is below 500000 then pass 2 is in place
	IF (mem_needed LT 500000 AND pass2_size_over_256 NE 0)
		flags = 1
	ENDIF
	DD	80000000h + flags SHL 26 + arch SHL 14 + clm SHL 6 + pass2_size_over_256
	DP	OFFSET procname
	DD	mem_needed
	ENDM

PRCENTRY MACRO procname, mem_needed, L2arg
	EXTRN	procname:PROC
	flags = 0
	IF (@INSTR (,@CATSTR(procname),_np_)) NE 0
		flags = flags + 4
	ENDIF
	IF (@INSTR (,@CATSTR(procname),_tp_)) NE 0
		flags = flags + 2
	ENDIF
	IF (@INSTR (,@CATSTR(procname),_ip_)) NE 0
		flags = flags + 1
	ENDIF
	IF (@INSTR (,@CATSTR(procname),_hg_)) NE 0
		fft_type = 0
	ELSEIF (@INSTR (,@CATSTR(procname),_r4_)) NE 0
		fft_type = 1
	ELSEIF (@INSTR (,@CATSTR(procname),_r4spm_)) NE 0
		fft_type = 2
	ELSEIF (@INSTR (,@CATSTR(procname),_r4r8_)) NE 0
		fft_type = 3
	ELSEIF (@INSTR (,@CATSTR(procname),_r4delay_)) NE 0
		fft_type = 4
	ELSE
		bad_sse2_fft_type
	ENDIF
	IF (@INSTR (,@CATSTR(procname),_P4)) NE 0
		arch = 2
	ELSEIF (@INSTR (,@CATSTR(procname),_CORE)) NE 0
		arch = 3
	ELSEIF (@INSTR (,@CATSTR(procname),_K8)) NE 0
		arch = 4
	ELSEIF (@INSTR (,@CATSTR(procname),_K10)) NE 0
		arch = 5
	ELSE
		bad_sse2_arch
	ENDIF
	IFB <L2arg>
		min_L2_cache = 0
	ELSEIF L2arg EQ 128
		min_L2_cache = 1
	ELSEIF L2arg EQ WILLI
		min_L2_cache = 2
	ELSEIF L2arg EQ CELE_D
		min_L2_cache = 3
	ELSEIF L2arg EQ 512
		min_L2_cache = 4
	ELSEIF L2arg EQ 1024
		min_L2_cache = 5
	ELSEIF L2arg EQ 2048
		min_L2_cache = 6
	ELSE
		bad_L2_cache
	ENDIF
	IF (@INSTR (,@CATSTR(procname),_1_)) NE 0
		clm = 1
	ELSEIF (@INSTR (,@CATSTR(procname),_2_)) NE 0
		clm = 2
	ELSEIF (@INSTR (,@CATSTR(procname),_4_)) NE 0
		clm = 4
	ELSEIF (@INSTR (,@CATSTR(procname),_8_)) NE 0
		clm = 8
	ELSE
		clm = 0
	ENDIF
	IF (@INSTR (,@CATSTR(procname),_10_)) NE 0
		pass2_size_over_256 = 1024 SHR 8
	ELSEIF (@INSTR (,@CATSTR(procname),_11_)) NE 0
		pass2_size_over_256 = 2048 SHR 8
	ELSEIF (@INSTR (,@CATSTR(procname),_2304_)) NE 0
		pass2_size_over_256 = 2304 SHR 8
	ELSEIF (@INSTR (,@CATSTR(procname),_3072_)) NE 0
		pass2_size_over_256 = 3072 SHR 8
	ELSEIF (@INSTR (,@CATSTR(procname),_12_)) NE 0
		pass2_size_over_256 = 4096 SHR 8
	ELSEIF (@INSTR (,@CATSTR(procname),_13_)) NE 0
		pass2_size_over_256 = 8192 SHR 8
	ELSEIF (@INSTR (,@CATSTR(procname),_8_)) NE 0
		pass2_size_over_256 = 256 SHR 8
	ELSE
		pass2_size_over_256 = 0
	ENDIF
	DD	80000000h + flags SHL 26 + fft_type SHL 18 + arch SHL 14 + min_L2_cache SHL 10 + clm SHL 6 + pass2_size_over_256
	DP	OFFSET procname
	DD	mem_needed
	ENDM

